#!/usr/bin/env node
// docs/evidence/schema.sql is the reviewer-friendly concatenation of supabase/migrations/*.sql (single source of truth:
// the migrations). Regenerate with `npm run db:evidence`; `--check` fails if it has drifted (also run by `npm test`).
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";

const root = resolve(import.meta.dirname, "..");
export function buildEvidence() {
  const dir = join(root, "supabase/migrations");
  const files = readdirSync(dir)
    .filter((f) => f.endsWith(".sql"))
    .sort();
  const header =
    "-- GENERATED by `npm run db:evidence` from supabase/migrations/*.sql. Do not edit by hand.\n" +
    "-- Reviewer copy of the schema (apply the migrations, not this file). Smoke checks: docs/evidence/schema-smoke.sql;\n" +
    "-- full tests: supabase/tests (npm run db:verify).\n";
  return (
    header +
    files.map((f) => `\n-- ===== ${f} =====\n${readFileSync(join(dir, f), "utf8")}`).join("")
  );
}
const target = join(root, "docs/evidence/schema.sql");
if (process.argv[1] && resolve(process.argv[1]) === resolve(import.meta.filename)) {
  const out = buildEvidence();
  if (process.argv.includes("--check")) {
    if (readFileSync(target, "utf8") !== out) {
      console.error("docs/evidence/schema.sql is out of date: run `npm run db:evidence`.");
      process.exit(1);
    }
    console.log("db:evidence: up to date");
  } else {
    writeFileSync(target, out);
    console.log(`wrote ${target}`);
  }
}
